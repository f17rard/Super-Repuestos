-- Migración para la historia de detalle del producto.
-- Ejecutar en Supabase SQL Editor después de revisar que public.repuestos.id es integer/serial
-- y que Supabase Auth está habilitado. No cambia las tablas existentes.

create table if not exists public.imagenes_repuestos (
  id bigint generated by default as identity primary key,
  repuesto_id integer not null references public.repuestos(id) on delete cascade,
  ruta_storage text not null,
  es_principal boolean not null default false,
  orden integer not null default 0,
  created_at timestamptz not null default now(),
  constraint imagenes_repuestos_ruta_unica unique (ruta_storage)
);

create index if not exists idx_imagenes_repuestos_repuesto_orden
  on public.imagenes_repuestos (repuesto_id, orden);

create table if not exists public.valoraciones_repuestos (
  id bigint generated by default as identity primary key,
  repuesto_id integer not null references public.repuestos(id) on delete cascade,
  usuario_id uuid not null references auth.users(id) on delete cascade,
  puntuacion smallint not null check (puntuacion between 1 and 5),
  opinion text not null check (char_length(trim(opinion)) between 1 and 1500),
  created_at timestamptz not null default now(),
  constraint valoracion_unica_por_usuario unique (repuesto_id, usuario_id)
);

create index if not exists idx_valoraciones_repuestos_repuesto_fecha
  on public.valoraciones_repuestos (repuesto_id, created_at desc);

create table if not exists public.favoritos (
  id bigint generated by default as identity primary key,
  usuario_id uuid not null references auth.users(id) on delete cascade,
  repuesto_id integer not null references public.repuestos(id) on delete cascade,
  created_at timestamptz not null default now(),
  constraint favorito_unico_por_usuario unique (usuario_id, repuesto_id)
);

create index if not exists idx_favoritos_usuario on public.favoritos (usuario_id);

alter table public.imagenes_repuestos enable row level security;
alter table public.valoraciones_repuestos enable row level security;
alter table public.favoritos enable row level security;

-- Catálogo de imágenes y opiniones legibles por usuarios no autenticados.
create policy "imagenes visibles para todos"
  on public.imagenes_repuestos for select using (true);
create policy "valoraciones visibles para todos"
  on public.valoraciones_repuestos for select using (true);

-- El usuario solo puede crear, modificar o eliminar sus propias valoraciones/favoritos.
create policy "usuario crea su valoracion"
  on public.valoraciones_repuestos for insert
  with check (auth.uid() = usuario_id);
create policy "usuario modifica su valoracion"
  on public.valoraciones_repuestos for update
  using (auth.uid() = usuario_id)
  with check (auth.uid() = usuario_id);
create policy "usuario elimina su valoracion"
  on public.valoraciones_repuestos for delete
  using (auth.uid() = usuario_id);

create policy "usuario ve sus favoritos"
  on public.favoritos for select using (auth.uid() = usuario_id);
create policy "usuario agrega sus favoritos"
  on public.favoritos for insert with check (auth.uid() = usuario_id);
create policy "usuario elimina sus favoritos"
  on public.favoritos for delete using (auth.uid() = usuario_id);

